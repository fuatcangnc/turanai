/**
 * Bundles the React widget into src/widget-bundle.generated.ts.
 *
 * A trusted plugin may use `page:fragments`, which accepts inline code; EmDash
 * forbids serving JavaScript from plugin routes, so the built bundle is handed
 * to the fragment hook as a string.
 */

import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

const result = await build({
	entryPoints: [path.join(root, "src/widget/main.tsx")],
	bundle: true,
	format: "iife",
	platform: "browser",
	target: ["chrome110", "safari16", "firefox115"],
	minify: true,
	legalComments: "none",
	define: { "process.env.NODE_ENV": '"production"' },
	write: false,
	jsx: "automatic",
});

const code = result.outputFiles[0].text;
writeFileSync(
	path.join(root, "src/widget-bundle.generated.ts"),
	[
		"// Generated by scripts/build-widget.mjs - do not edit.",
		`export const TURAN_WIDGET_BUNDLE = ${JSON.stringify(code)};`,
		"",
	].join("\n"),
);
console.log(`widget bundle written (${(code.length / 1024).toFixed(1)} kB)`);
